/// Get the 8x8 font bitmap for any unicode character, with Latin-1,
/// typographic, and base Latin fallbacks so characters are never lost.
#[inline]
pub fn get_glyph(cp: char) -> [u8; 8] {
    let u = cp as u32;
    if u < 128 {
        return GLYPHS[u as usize];
    }
    if (128..256).contains(&u) {
        return LATIN1_GLYPHS[(u - 128) as usize];
    }

    // Common Unicode punctuation and symbols
    match cp {
        // Smart quotes & apostrophes
        '‘' | '’' | '′' | '`' => LATIN1_GLYPHS[0x11], // 0x91
        '“' | '”' | '″' => LATIN1_GLYPHS[0x13],       // 0x93
        '„' => LATIN1_GLYPHS[0x04],                   // 0x84
        '‚' => LATIN1_GLYPHS[0x02],                   // 0x82

        // Dashes
        '—' | '―' => LATIN1_GLYPHS[0x17], // 0x97 (em dash)
        '–' | '‒' | '−' => LATIN1_GLYPHS[0x16], // 0x96 (en dash)

        // Bullets & ellipsis
        '•' | '◦' | '‣' => LATIN1_GLYPHS[0x15], // 0x95
        '…' => LATIN1_GLYPHS[0x05],            // 0x85
        '€' => LATIN1_GLYPHS[0x00],            // 0x80
        '™' => LATIN1_GLYPHS[0x19],            // 0x99

        // Arrows & math
        '←' => [0x00, 0x08, 0x04, 0x7E, 0x04, 0x08, 0x00, 0x00],
        '→' => [0x00, 0x10, 0x20, 0x7E, 0x20, 0x10, 0x00, 0x00],
        '↑' => [0x00, 0x18, 0x3C, 0x7E, 0x18, 0x18, 0x18, 0x00],
        '↓' => [0x00, 0x18, 0x18, 0x18, 0x7E, 0x3C, 0x18, 0x00],
        '↔' => [0x00, 0x00, 0x24, 0x7E, 0x24, 0x00, 0x00, 0x00],
        '✓' | '✔' => [0x00, 0x01, 0x03, 0x46, 0x6C, 0x38, 0x10, 0x00],
        '≤' => [0x18, 0x0C, 0x06, 0x03, 0x06, 0x0C, 0x18, 0x3F],
        '≥' => [0x06, 0x0C, 0x18, 0x30, 0x18, 0x0C, 0x06, 0x3F],
        '≠' => [0x08, 0x3F, 0x10, 0x00, 0x00, 0x3F, 0x20, 0x00],
        '∞' => [0x00, 0x00, 0x3C, 0x42, 0x3C, 0x42, 0x3C, 0x00],

        // Latin Extended base fallbacks for European languages
        'Ā' | 'Ă' | 'Ą' => GLYPHS['A' as usize],
        'ā' | 'ă' | 'ą' => GLYPHS['a' as usize],
        'Ć' | 'Ĉ' | 'Ċ' | 'Č' => GLYPHS['C' as usize],
        'ć' | 'ĉ' | 'ċ' | 'č' => GLYPHS['c' as usize],
        'Ď' | 'Đ' => GLYPHS['D' as usize],
        'ď' | 'đ' => GLYPHS['d' as usize],
        'Ē' | 'Ĕ' | 'Ė' | 'Ę' | 'Ě' => GLYPHS['E' as usize],
        'ē' | 'ĕ' | 'ė' | 'ę' | 'ě' => GLYPHS['e' as usize],
        'Ğ' | 'Ġ' | 'Ģ' => GLYPHS['G' as usize],
        'ğ' | 'ġ' | 'ģ' => GLYPHS['g' as usize],
        'Ĥ' | 'Ħ' => GLYPHS['H' as usize],
        'ĥ' | 'ħ' => GLYPHS['h' as usize],
        'Ĩ' | 'Ī' | 'Ĭ' | 'Į' | 'İ' => GLYPHS['I' as usize],
        'ĩ' | 'ī' | 'ĭ' | 'į' | 'ı' => GLYPHS['i' as usize],
        'Ĵ' => GLYPHS['J' as usize],
        'ĵ' => GLYPHS['j' as usize],
        'Ķ' => GLYPHS['K' as usize],
        'ķ' => GLYPHS['k' as usize],
        'Ĺ' | 'Ļ' | 'Ľ' | 'Ł' => GLYPHS['L' as usize],
        'ĺ' | 'ļ' | 'ľ' | 'ł' => GLYPHS['l' as usize],
        'Ń' | 'Ņ' | 'Ň' | 'Ŋ' => GLYPHS['N' as usize],
        'ń' | 'ņ' | 'ň' | 'ŋ' => GLYPHS['n' as usize],
        'Ō' | 'Ŏ' | 'Ő' => GLYPHS['O' as usize],
        'ō' | 'ŏ' | 'ő' => GLYPHS['o' as usize],
        'Ŕ' | 'Ŗ' | 'Ř' => GLYPHS['R' as usize],
        'ŕ' | 'ŗ' | 'ř' => GLYPHS['r' as usize],
        'Ś' | 'Ŝ' | 'Ş' | 'Š' => LATIN1_GLYPHS[0x0A],
        'ś' | 'ŝ' | 'ş' | 'š' => LATIN1_GLYPHS[0x1A],
        'Ţ' | 'Ť' | 'Ŧ' => GLYPHS['T' as usize],
        'ţ' | 'ť' | 'ŧ' => GLYPHS['t' as usize],
        'Ũ' | 'Ū' | 'Ŭ' | 'Ů' | 'Ű' | 'Ų' => GLYPHS['U' as usize],
        'ũ' | 'ū' | 'ŭ' | 'ů' | 'ű' | 'ų' => GLYPHS['u' as usize],
        'Ŵ' => GLYPHS['W' as usize],
        'ŵ' => GLYPHS['w' as usize],
        'Ŷ' => GLYPHS['Y' as usize],
        'ŷ' => GLYPHS['y' as usize],
        'Ź' | 'Ż' | 'Ž' => LATIN1_GLYPHS[0x0E],
        'ź' | 'ż' | 'ž' => LATIN1_GLYPHS[0x1E],

        _ => GLYPHS[63], // '?'
    }
}
